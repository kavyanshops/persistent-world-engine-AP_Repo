CREATE SCHEMA IF NOT EXISTS shelter_ops;
SET search_path TO shelter_ops;

CREATE TABLE species (
    species_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_name text NOT NULL UNIQUE,
    average_lifespan integer CHECK (average_lifespan > 0),
    is_domestic boolean NOT NULL DEFAULT true
);

CREATE TABLE shelters (
    shelter_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shelter_name text NOT NULL UNIQUE,
    city text NOT NULL,
    state text NOT NULL,
    postal_code varchar(6) NOT NULL
        CHECK (postal_code ~ '^[0-9]{6}$'),
    capacity integer NOT NULL CHECK (capacity > 0),
    contact_email text NOT NULL UNIQUE
        CHECK (position('@' IN contact_email) > 1),
    established_on date NOT NULL
);

CREATE TABLE animals (
    animal_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_name text NOT NULL
        CHECK (length(trim(animal_name)) > 0),
    species_id integer NOT NULL
        REFERENCES species(species_id) ON DELETE RESTRICT,
    shelter_id integer NOT NULL
        REFERENCES shelters(shelter_id) ON DELETE RESTRICT,
    gender text NOT NULL CHECK (gender IN ('MALE', 'FEMALE')),
    date_of_birth date,
    intake_date date NOT NULL,
    color text NOT NULL,
    weight numeric(6,2) CHECK (weight > 0),
    health_status text NOT NULL DEFAULT 'HEALTHY'
        CHECK (health_status IN ('HEALTHY', 'UNDER_TREATMENT', 'RECOVERING')),
    adoption_status text NOT NULL DEFAULT 'AVAILABLE'
        CHECK (adoption_status IN ('AVAILABLE', 'RESERVED', 'ADOPTED')),
    microchip_number varchar(20) UNIQUE,
    CHECK (date_of_birth IS NULL OR date_of_birth <= intake_date)
);

CREATE TABLE adopters (
    adopter_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL
        CHECK (length(trim(full_name)) > 0),
    email text NOT NULL UNIQUE
        CHECK (position('@' IN email) > 1),
    phone varchar(16) NOT NULL UNIQUE
        CHECK (phone ~ '^\+?[0-9]{10,15}$'),
    address text NOT NULL,
    city text NOT NULL,
    occupation text,
    registration_date date NOT NULL DEFAULT CURRENT_DATE,
    is_verified boolean NOT NULL DEFAULT false,
    has_previous_experience boolean NOT NULL DEFAULT false
);

CREATE TABLE adoption_applications (
    application_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id integer NOT NULL
        REFERENCES animals(animal_id) ON DELETE RESTRICT,
    adopter_id integer NOT NULL
        REFERENCES adopters(adopter_id) ON DELETE RESTRICT,
    application_date date NOT NULL DEFAULT CURRENT_DATE,
    housing_type text NOT NULL
        CHECK (housing_type IN ('APARTMENT', 'HOUSE', 'FARM')),
    has_other_pets boolean NOT NULL DEFAULT false,
    reason text NOT NULL CHECK (length(trim(reason)) > 10),
    application_status text NOT NULL DEFAULT 'PENDING'
        CHECK (application_status IN ('PENDING', 'APPROVED', 'REJECTED', 'WITHDRAWN')),
    reviewed_on date,
    UNIQUE (animal_id, adopter_id),
    CHECK (reviewed_on IS NULL OR reviewed_on >= application_date),
    CHECK (application_status <> 'APPROVED' OR reviewed_on IS NOT NULL)
);

CREATE TABLE shelter_staff (
    staff_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shelter_id integer NOT NULL
        REFERENCES shelters(shelter_id) ON DELETE CASCADE,
    full_name text NOT NULL,
    email text NOT NULL UNIQUE,
    phone varchar(16) NOT NULL,
    job_role text NOT NULL
        CHECK (job_role IN ('VETERINARIAN', 'CAREGIVER', 'MANAGER')),
    joining_date date NOT NULL,
    monthly_salary numeric(10,2) NOT NULL
        CHECK (monthly_salary >= 0),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE shelter_visits (
    visit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id integer NOT NULL
        REFERENCES adoption_applications(application_id) ON DELETE CASCADE,
    staff_id integer NOT NULL
        REFERENCES shelter_staff(staff_id) ON DELETE RESTRICT,
    visit_date date NOT NULL,
    visit_time time NOT NULL,
    visit_status text NOT NULL DEFAULT 'SCHEDULED'
        CHECK (visit_status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
    visitor_feedback text,
    UNIQUE (application_id, visit_date, visit_time)
);

CREATE TABLE adoptions (
    adoption_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id integer NOT NULL UNIQUE
        REFERENCES adoption_applications(application_id) ON DELETE RESTRICT,
    adoption_date date NOT NULL DEFAULT CURRENT_DATE,
    adoption_fee numeric(8,2) NOT NULL DEFAULT 0
        CHECK (adoption_fee >= 0),
    payment_status text NOT NULL DEFAULT 'PENDING'
        CHECK (payment_status IN ('PENDING', 'PAID', 'WAIVED')),
    agreement_signed boolean NOT NULL DEFAULT false,
    return_date date,
    return_reason text,
    CHECK (return_date IS NULL OR return_date >= adoption_date),
    CHECK (return_date IS NULL OR return_reason IS NOT NULL)
);

CREATE TABLE medical_records (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id integer NOT NULL
        REFERENCES animals(animal_id) ON DELETE CASCADE,
    staff_id integer NOT NULL
        REFERENCES shelter_staff(staff_id) ON DELETE RESTRICT,
    treatment_type text NOT NULL
        CHECK (treatment_type IN ('CHECKUP', 'VACCINATION', 'SURGERY', 'MEDICATION')),
    diagnosis text NOT NULL,
    treatment_date date NOT NULL DEFAULT CURRENT_DATE,
    next_checkup date,
    treatment_cost numeric(9,2) NOT NULL DEFAULT 0
        CHECK (treatment_cost >= 0),
    notes text,
    CHECK (next_checkup IS NULL OR next_checkup >= treatment_date)
);

CREATE TABLE donations (
    donation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adopter_id integer
        REFERENCES adopters(adopter_id) ON DELETE SET NULL,
    shelter_id integer NOT NULL
        REFERENCES shelters(shelter_id) ON DELETE RESTRICT,
    donation_amount numeric(10,2) NOT NULL
        CHECK (donation_amount > 0),
    donation_date date NOT NULL DEFAULT CURRENT_DATE,
    donation_type text NOT NULL
        CHECK (donation_type IN ('MONEY', 'FOOD', 'MEDICINE', 'EQUIPMENT')),
    payment_method text
        CHECK (payment_method IN ('UPI', 'CASH', 'CARD', 'BANK_TRANSFER')),
    receipt_number text UNIQUE,
    is_anonymous boolean NOT NULL DEFAULT false,
    CHECK (NOT is_anonymous OR adopter_id IS NULL)
);